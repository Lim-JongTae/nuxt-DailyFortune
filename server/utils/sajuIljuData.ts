/**
 * 일주 코드로 상세 데이터 조회 (0.001초)
 */
export function getIljuDetailByCode(code: string): SajuIljuDetail | null {
  if (!code) return null
  return iljuByCodeMap[code.toLowerCase()] || null
}

/**
 * 일주 순번(1~60)으로 상세 데이터 조회
 */
export function getIljuDetailByOrder(order: number): SajuIljuDetail | null {
  if (order < 1 || order > 60) return null
  return iljuByOrderMap[order] || null
}
